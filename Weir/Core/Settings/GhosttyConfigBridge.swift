// GhosttyConfigBridge.swift
// Weir — translates `WeirSettings` into the `key = value\n` text
// libghostty parses, and applies it to the running app. The forced
// keys (transparent pane, paste protection, …) go *last* in the file,
// after the keybinds, so libghostty's last-write-wins merge silently
// overrides anything the user, `~/.config/ghostty/config`, or our
// own earlier lines wrote — cheaper than pre-parsing to filter.

import CryptoKit
import Foundation
import GhosttyKit
import OSLog
import WeirDomain

private let log = Logger.weir("ghostty.config-bridge")

enum GhosttyConfigReloadError: WeirLocalizedError, Equatable {
    case layerWriteFailed
    case configCreationFailed

    var message: DisplayText {
        switch self {
        case .layerWriteFailed:
            .localized("Weir couldn’t write the terminal configuration.")
        case .configCreationFailed:
            .localized("Weir couldn’t create the terminal configuration.")
        }
    }
}

@MainActor
enum GhosttyConfigBridge {
    /// Horizontal padding, in points, we give every surface through
    /// `window-padding-x`. See `makeConfigString` for why. The quick
    /// terminal subtracts it from its own inset, so both read this value.
    nonisolated static let windowPaddingX = 8

    /// Vertical padding, in points, we give every surface through
    /// `window-padding-y`. We own it for the reason we own the horizontal
    /// one. The quick terminal subtracts it too, which needs the padding
    /// libghostty will apply, and the C API cannot read a user's value back.
    nonisolated static let windowPaddingY = 8

    // MARK: - Serialization

    /// Build the full `key = value\n` string Weir wants libghostty
    /// to evaluate. Order matters: user-facing settings first, then the
    /// keybinds, so the forced-overrides section at the bottom always wins.
    /// `shell` replaces the person's login shell in every pane; demo mode
    /// names its own (`DemoFixture.shellCommand`), and nothing else does.
    ///
    /// The `theme` line names the copies `writeConfigFile` writes under
    /// `themeDirectory` (`themeCopyDirectory` when `nil`) for any theme
    /// Weir does not ship. A copy is named by its colors, so the text differs
    /// whenever what libghostty would load differs. This function only
    /// reads; the copies are written with the config.
    static func makeConfigString(
        settings: WeirSettings,
        resourcesDir: String?,
        themeCatalog: TerminalThemeCatalog? = nil,
        themeDirectory: URL? = nil,
        processID: Int32 = ProcessInfo.processInfo.processIdentifier,
        shell: String? = defaultShell
    ) -> String {
        let theme = resolveTheme(
            selection: settings.appearance.terminalTheme,
            resourcesDir: resourcesDir,
            catalog: themeCatalog
        )
        return makeConfigString(
            settings: settings,
            resourcesDir: resourcesDir,
            themePaths: theme.map {
                themePaths(for: $0, directory: themeDirectory?.path ?? themeCopyDirectory, processID: processID)
            },
            shell: shell
        )
    }

    /// The shell every pane runs in place of the login shell: demo mode's
    /// own, else none.
    static var defaultShell: String? {
        DemoFixture.isDemoActive ? DemoFixture.shellCommand : nil
    }

    /// Weir's folder for the files libghostty reads once: the config and
    /// the read-back probes.
    static var temporaryDirectory: String {
        (NSTemporaryDirectory() as NSString).appendingPathComponent("com.nekoder.weir")
    }

    /// Weir's folder for the theme copies, under Application Support rather
    /// than `temporaryDirectory`. libghostty opens a copy again on every
    /// appearance switch, however long after the config was written, and
    /// macOS removes files in the temporary folder that have gone days
    /// unused; a copy removed there would leave the terminal without its
    /// theme at the next switch while Weir still paints the theme's ground.
    static var themeCopyDirectory: String {
        WeirPaths.applicationSupportDirectory().appendingPathComponent("terminal-themes", isDirectory: true).path
    }

    /// `makeConfigString(settings:resourcesDir:…)` with the theme files
    /// already chosen; `nil` writes no `theme` line.
    private static func makeConfigString(
        settings: WeirSettings,
        resourcesDir: String?,
        themePaths: TerminalThemePaths?,
        shell: String?
    ) -> String {
        var lines: [String] = [
            "# Generated by Weir. Edits here are overwritten on every settings change.",
            "# Settings UI: \(StandardMenuShortcut.settings.displayString) — file: \(SettingsStore.defaultSettingsFileURL.path)",
            ""
        ]

        // MARK: - User-facing settings → libghostty keys

        // Font
        if let family = settings.font.family, !family.isEmpty {
            // Strip any line terminator the value happens to carry —
            // libghostty's config is line-oriented, so an embedded
            // newline in a hand-edited `settings.json` would otherwise
            // inject extra config keys (`window-decoration = client`,
            // `command = …`). The forced-overrides block comes later and
            // still wins, but keys outside it would stick. The
            // picker only offers `NSFontManager` families today, but
            // defensive sanitization at the splice site is cheap.
            let sanitized = family.replacingOccurrences(of: "\n", with: " ")
                .replacingOccurrences(of: "\r", with: " ")
            lines.append("font-family = \(sanitized)")
        }
        lines.append("font-size = \(settings.font.size)")
        if settings.font.ligatures {
            // Empty value clears libghostty's default "calt = 0" so
            // ligatures activate. Non-empty enables specific
            // OpenType features — left as default for now.
            lines.append("font-feature = ")
        } else {
            lines.append("font-feature = -calt")
        }
        if settings.font.lineHeight != 0 {
            lines.append("adjust-cell-height = \(Int(settings.font.lineHeight))")
        }

        // Terminal
        // The UI expresses this preference in lines. Ghostty's legacy
        // `scrollback-limit` spelling means bytes, while the explicit lines
        // key preserves the contract the picker presents. Remove the separate
        // byte ceiling so it cannot truncate history before the selected line
        // limit; allocation remains lazy and Ghostty compresses idle history.
        lines.append("scrollback-limit-lines = \(settings.terminal.scrollbackLines)")
        lines.append("scrollback-limit-bytes = unlimited")
        lines.append("cursor-style = \(mapCursorStyle(settings.terminal.cursorStyle))")
        lines.append("cursor-style-blink = \(settings.terminal.cursorBlink.isOn)")

        // Breathing room between the cell grid and the pane's edges.
        // The pane is flush to its column, because a full-width row —
        // a tmux status bar is the one that shows it — has to reach the
        // edge, and a SwiftUI padding around the surface would inset
        // that row along with everything else. Padding the grid from
        // inside the terminal separates the two: `extend` carries the
        // nearest cell's background into the padding, so a colored
        // full-width row still runs edge to edge while ordinary text
        // keeps its margin. libghostty's own default is 2, which reads
        // as no margin at all once the pane stopped being inset.
        lines.append("window-padding-x = \(windowPaddingX)")
        lines.append("window-padding-y = \(windowPaddingY)")
        lines.append("window-padding-color = extend")

        // Theme: the person's choice for each side, else the bundled
        // `Apple System Colors` pair, whose cell foreground and ANSI palette
        // track macOS Terminal.app. Every side is an absolute path because
        // libghostty's named-theme lookup checks only the user folder
        // (`$XDG_CONFIG_HOME/ghostty/themes/`) and the `themes` folder of its
        // resources directory (`GHOSTTY_RESOURCES_DIR`). A name alone would
        // resolve against the first of those that has it, not the folder the
        // person chose it from, and never against an installed Ghostty app.
        // A theme Weir does not ship is named by its color-only copy
        // (`TerminalThemeSource`). Only a path with a line break cannot be
        // written; libghostty then falls back to its own colors.
        if let themePaths, let line = themeLine(light: themePaths.light, dark: themePaths.dark) {
            lines.append(line)
        }

        // MARK: - Pattern A — single source of truth for keybinds

        //
        // Wipe libghostty's built-in macOS defaults so the menu bar
        // owns every shortcut; without `clear` a user remap (e.g.
        // "New Tab" → ⌘⇧T) would leave libghostty still firing its
        // own ⌘T behind the user's back. Forced bindings + the
        // user-configured action keybinds get re-emitted below.
        lines.append("keybind = clear")
        // Defense-in-depth against libghostty's `super+q=quit`
        // racing AppKit's terminate path (which fires
        // `applicationWillTerminate` and persists scrollback). ⌘Q is
        // already routed to the menu via
        // `SurfaceView.performKeyEquivalent`, but unbinding here
        // covers any future keystroke-routing change.
        lines.append("keybind = super+q=unbind")
        // Legacy XTerm key encoding emits identical bytes for ↩
        // and ⇧↩, so TUIs can't tell them apart. Mapping ⇧↩ to a
        // literal newline matches the recommended bare-ghostty
        // workaround (ghostty discussion #7780).
        lines.append(#"keybind = shift+enter=text:\n"#)

        lines.append(contentsOf: actionKeybindLines(settings: settings))
        lines.append(contentsOf: numberJumpKeybindLines())

        // MARK: - Forced overrides

        // These go LAST, after the keybinds too, so libghostty's
        // last-write-wins merging keeps them even if user config or an
        // earlier line of ours set them otherwise.

        lines.append("")
        lines.append("# Weir forced overrides — do not override these in user config.")
        lines.append("# Liquid Glass toolbar relies on these exact values.")
        // Terminal cells stay fully transparent — the wallpaper /
        // window opacity is the user-facing transparency knob, not
        // libghostty's per-cell tint. The theme still colors only text
        // and the ANSI palette here; Weir paints the theme's background
        // under the terminal area itself (`PaneContainerView`), at the
        // surface's opacity, from the palette `readBackPalettes` reads.
        lines.append("background-opacity = 0")
        // libghostty exports the database beside its resources directory as
        // TERMINFO. Check the exact compiled alias before advertising it so a
        // partial development/package build falls back instead of leaving
        // every curses program unable to resolve $TERM.
        lines.append("term = \(resolvedTerm(resourcesDir: resourcesDir))")
        // Weir handles its own close-confirm via SwiftUI .alert,
        // so disable libghostty's confirm dialog.
        lines.append("confirm-close-surface = false")
        // Review pastes repository content — a diff an agent wrote, or one
        // that arrived with a clone — into whatever the pane is running. The
        // confirmation an unbracketed multi-line paste goes through is what
        // keeps a shell from taking those lines as commands, so it is not a
        // setting a layered user config may switch off.
        lines.append("clipboard-paste-protection = true")
        // Tell shell integration to keep its hands off the cursor. Preserve
        // the bundled TERMINFO through local sudo, and keep SSH compatible
        // with hosts that do not have xterm-ghostty installed. We do not turn
        // on ssh-terminfo because silently installing files on a remote host
        // exceeds an embedded terminal's local configuration responsibility.
        // Default zsh / fish integration sends DECSCUSR (`ESC[<n> q`)
        // on every prompt, which clobbers Weir's `cursor-style`
        // preference on the next keystroke. We own this setting
        // through Settings → Terminal → Cursor, so the prompt-time
        // override is always wrong here. (See Ghostty discussions
        // #3836 / #5144 / #8681 — the long-standing pitfall behind
        // "cursor-style doesn't change on existing shells".)
        lines.append("shell-integration-features = no-cursor,sudo,ssh-env")
        // Weir never loads custom shaders, so disable the draw timer
        // that fires at 120 Hz (DRAW_INTERVAL = 8 ms) when the surface
        // is focused. Without this, every focused surface burns ~120
        // wakeups/s even at idle.
        lines.append("custom-shader-animation = false")
        // Demo mode types its scenes into each pane's shell, which must not
        // be the person's own (`DemoFixture.shellCommand`). We name it here
        // rather than per surface: a surface's own command makes libghostty
        // keep the pane open after its shell exits. `initial-command` too, as
        // a user config's would replace it for the first pane.
        if let shell {
            lines.append("command = \(shell)")
            lines.append("initial-command = \(shell)")
        }

        return lines.joined(separator: "\n") + "\n"
    }

    // MARK: - Terminal theme

    /// Where one side of the `theme` line gets its file.
    ///
    /// libghostty loads a theme file as a config file, so a theme can set
    /// any key, `command` and `initial-command` among them, and change what
    /// a new pane runs. Only a theme Weir ships is named as it is; for any
    /// other, Weir keeps the file's color lines (`TerminalThemeFile.sanitized(_:)`)
    /// and names a copy of those instead, so a theme can change colors and
    /// nothing else.
    enum TerminalThemeSource: Equatable {
        /// A theme in Weir's bundle, named by its absolute path.
        case bundled(path: String)
        /// The color lines of a theme from any other folder, which
        /// `writeConfigFile` writes to Weir's copy for the side.
        case sanitized(String)
    }

    /// The source of each side of the theme, and the sides whose chosen
    /// theme could not be used.
    struct ResolvedTerminalTheme: Equatable {
        var light: TerminalThemeSource
        var dark: TerminalThemeSource
        /// The chosen refs that could not be used, by side: missing,
        /// unreadable, larger than `TerminalThemeFile.maxBytes`, or without
        /// a `background` we can read. Each such side uses the bundled
        /// default. Empty when every choice was used, or when nothing was
        /// chosen.
        var fallbacks: [TerminalThemeBrightness: TerminalThemeRef] = [:]

        func source(for side: TerminalThemeBrightness) -> TerminalThemeSource {
            switch side {
            case .light: light
            case .dark: dark
            }
        }
    }

    /// The theme file each side of the `theme` line names, and the sides
    /// whose chosen theme could not be used.
    struct TerminalThemePaths: Equatable {
        var light: String
        var dark: String
        /// See `ResolvedTerminalTheme.fallbacks`.
        var fallbacks: [TerminalThemeBrightness: TerminalThemeRef] = [:]
    }

    /// The theme files the config `writeConfigFile` last wrote names, so
    /// the read-back probes the same copies libghostty loaded. `nil` before
    /// the first write, or when the resources folder is unknown.
    private(set) static var writtenThemePaths: TerminalThemePaths?

    /// The bundled theme each side uses when nothing usable is chosen.
    nonisolated static func defaultThemeRef(for side: TerminalThemeBrightness) -> TerminalThemeRef {
        switch side {
        case .light: TerminalThemeRef(name: "Apple System Colors Light", origin: .bundled)
        case .dark: TerminalThemeRef(name: "Apple System Colors", origin: .bundled)
        }
    }

    /// The path of `defaultThemeRef(for:)` under `resourcesDir`.
    static func defaultThemePath(for side: TerminalThemeBrightness, resourcesDir: String) -> String {
        "\(resourcesDir)/themes/\(defaultThemeRef(for: side).name)"
    }

    /// Weir's copy of `colors`, the color lines of the theme on `side`.
    ///
    /// The name ends with the first 16 hex digits of the colors' SHA-256, so
    /// a path never changes what it holds. libghostty opens the copy again
    /// on every appearance switch; were one name reused for new colors, a
    /// reload that failed after writing them would leave the running config
    /// naming a file that no longer matches the ground Weir paints. The
    /// process ID keeps concurrent Dev and Release instances apart, as it
    /// does for the config file (`themeCopyPrefix`).
    static func themeCopyPath(
        for side: TerminalThemeBrightness,
        colors: String,
        directory: String,
        processID: Int32
    ) -> String {
        let digest = SHA256.hash(data: Data(colors.utf8))
        let hex = digest.prefix(8).map { String(format: "%02x", $0) }.joined()
        let name = themeCopyPrefix(processID: processID) + "\(side.rawValue)-\(hex).weir"
        return (directory as NSString).appendingPathComponent(name)
    }

    /// The start of every theme copy's name for `processID`. The trailing
    /// `-` keeps one process's prefix from matching another whose ID starts
    /// with the same digits.
    nonisolated static func themeCopyPrefix(processID: Int32) -> String {
        "ghostty-theme-\(processID)-"
    }

    /// Removes the theme copies under `directory` (`themeCopyDirectory`
    /// when `nil`) that no running config can name: those of `processID`
    /// that `installed` does not name, and those of a process that has
    /// exited.
    ///
    /// Call it only once the config naming `installed` is in use: until
    /// then the running config may still name an older copy, which
    /// libghostty opens again on an appearance switch. A live process's
    /// copies and the probe files are left alone. The folder outlives the
    /// processes that wrote into it, so without the second rule every
    /// launch would leave its copies behind.
    static func removeStaleThemeCopies(
        keeping installed: TerminalThemePaths?,
        directory: URL? = nil,
        processID: Int32 = ProcessInfo.processInfo.processIdentifier,
        isAlive: (Int32) -> Bool = { kill($0, 0) == 0 || errno == EPERM }
    ) {
        let dir = directory?.path ?? themeCopyDirectory
        let kept = Set([installed?.light, installed?.dark].compactMap(\.self))
        // A folder that cannot be listed holds nothing we wrote.
        guard let names = try? FileManager.default.contentsOfDirectory(atPath: dir) else { return }
        for name in names where name.hasSuffix(".weir") {
            guard let owner = themeCopyOwner(of: name) else { continue }
            let path = (dir as NSString).appendingPathComponent(name)
            if owner == processID {
                guard !kept.contains(path) else { continue }
            } else {
                guard !isAlive(owner) else { continue }
            }
            do {
                try TestWriteGuard.check(URL(fileURLWithPath: path))
                try FileManager.default.removeItem(atPath: path)
            } catch {
                log.error("theme copy removal failed: \(String(describing: error), privacy: .private)")
            }
        }
    }

    /// The process ID a theme copy's name starts with (`themeCopyPrefix`),
    /// or `nil` for a name that is not a theme copy, a probe file included.
    nonisolated static func themeCopyOwner(of name: String) -> Int32? {
        let start = "ghostty-theme-"
        guard name.hasPrefix(start) else { return nil }
        let digits = name.dropFirst(start.count).prefix { $0.isNumber }
        guard !digits.isEmpty, name.dropFirst(start.count + digits.count).hasPrefix("-") else { return nil }
        return Int32(digits)
    }

    /// Resolves each side of `selection`, or returns `nil` when
    /// `resourcesDir` is unknown: the bundled defaults live there, and
    /// without them there is no theme to fall back to.
    ///
    /// A side left at its default is built from `resourcesDir` alone, with
    /// no file check, so the default line names the bundled pair's paths
    /// whatever the folders hold. A chosen theme outside the bundle is read
    /// here, at most `TerminalThemeFile.maxBytes`, and only its color lines
    /// are kept. Nothing is written. `catalog` defaults to the folders a
    /// running Weir reads and is built only when a side holds a choice.
    static func resolveTheme(
        selection: TerminalThemeSelection,
        resourcesDir: String?,
        catalog: TerminalThemeCatalog? = nil
    ) -> ResolvedTerminalTheme? {
        guard let resourcesDir else { return nil }
        var resolvedCatalog = catalog
        var fallbacks: [TerminalThemeBrightness: TerminalThemeRef] = [:]
        func source(for side: TerminalThemeBrightness, ref: TerminalThemeRef?) -> TerminalThemeSource {
            let fallback = TerminalThemeSource.bundled(path: defaultThemePath(for: side, resourcesDir: resourcesDir))
            guard let ref else { return fallback }
            let catalog = resolvedCatalog ?? TerminalThemeCatalog(resourcesDir: resourcesDir)
            resolvedCatalog = catalog
            guard let path = catalog.resolve(ref) else {
                fallbacks[side] = ref
                return fallback
            }
            if ref.origin == .bundled {
                // The catalog refuses unusable names; we check the whole
                // path again here because its folder came from the
                // environment and the line is what libghostty parses.
                guard isWritableThemePath(path) else {
                    fallbacks[side] = ref
                    return fallback
                }
                return .bundled(path: path)
            }
            guard let text = TerminalThemeCatalog.readThemeText(atPath: path),
                  let colors = TerminalThemeFile.sanitized(text)
            else {
                fallbacks[side] = ref
                return fallback
            }
            return .sanitized(colors)
        }
        let light = source(for: .light, ref: selection.light)
        let dark = source(for: .dark, ref: selection.dark)
        return ResolvedTerminalTheme(light: light, dark: dark, fallbacks: fallbacks)
    }

    /// The file each side of `theme` names: a bundled theme's own path, or
    /// Weir's copy under `directory` for any other.
    static func themePaths(
        for theme: ResolvedTerminalTheme,
        directory: String,
        processID: Int32 = ProcessInfo.processInfo.processIdentifier
    ) -> TerminalThemePaths {
        func path(_ side: TerminalThemeBrightness) -> String {
            switch theme.source(for: side) {
            case let .bundled(path): path
            case let .sanitized(colors):
                themeCopyPath(for: side, colors: colors, directory: directory, processID: processID)
            }
        }
        return TerminalThemePaths(light: path(.light), dark: path(.dark), fallbacks: theme.fallbacks)
    }

    /// The bundled default pair's paths, which never need a copy.
    static func defaultThemePaths(resourcesDir: String?) -> TerminalThemePaths? {
        resolveTheme(selection: TerminalThemeSelection(), resourcesDir: resourcesDir).map {
            themePaths(for: $0, directory: themeCopyDirectory)
        }
    }

    /// Whether `path` can be written into a `theme` line at all.
    private static func isWritableThemePath(_ path: String) -> Bool {
        themeLineValue(path) != nil
    }

    /// The `theme` line naming `light` and `dark`, or `nil` when either
    /// cannot be written. The running config and the probes both use it,
    /// so a probe reads the files the running config names.
    static func themeLine(light: String, dark: String) -> String? {
        guard let light = themeLineValue(light), let dark = themeLineValue(dark) else { return nil }
        return "theme = light:\(light),dark:\(dark)"
    }

    /// One side's path as the `theme` line holds it, or `nil` for a path
    /// with a line break, which would end the line.
    ///
    /// libghostty splits the `light:…,dark:…` value on `,`, treats `"` as
    /// the start of a quoted part and `\` as an escape, and trims spaces and
    /// tabs around each side. A path with any of those is written as a
    /// double-quoted string with `\` and `"` escaped, which libghostty
    /// decodes back to the path (`CommaSplitter.zig`, `parseAutoStruct` in
    /// `args.zig`). Any other path is written as it is, so a line without
    /// those characters holds the plain paths.
    nonisolated static func themeLineValue(_ path: String) -> String? {
        guard !path.contains(where: \.isNewline) else { return nil }
        let isTrimmed: (Character) -> Bool = { $0 == " " || $0 == "\t" }
        let needsQuotes = path.contains { ",\"\\".contains($0) }
            || path.first.map(isTrimmed) == true
            || path.last.map(isTrimmed) == true
        guard needsQuotes else { return path }
        let escaped = path.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
        return "\"\(escaped)\""
    }

    /// Returns the palette libghostty resolves for each side of
    /// `themePaths`, or `nil` for a side whose probe could not be built.
    ///
    /// Pass the paths the running config names (`writtenThemePaths`), so a
    /// probe loads the same theme copies libghostty loaded: the painted
    /// ground and the terminal's colors then come from one reading of the
    /// theme file.
    ///
    /// A finalized config evaluates only the light side of a `light:…,dark:…`
    /// pair, so we build one probe config per side whose theme line names
    /// that side's file for both. With `includeUserConfig` a probe loads the
    /// person's Ghostty config first, as the running config does, so its
    /// colors win over the theme's there too. `userConfigPath` stands in for
    /// that config in tests, which must not run libghostty's default-file
    /// loader: it can create a template config under the real
    /// `~/Library/Application Support`. Production passes `nil`. A probe
    /// neither records a read of that config (`userConfigReadAt`) nor
    /// touches the running config's file. Probe files are written under
    /// `directory`, or Weir's temporary folder, and removed once read.
    static func readBackPalettes(
        themePaths: TerminalThemePaths?,
        includeUserConfig: Bool,
        userConfigPath: String? = nil,
        directory: URL? = nil,
        processID: Int32 = ProcessInfo.processInfo.processIdentifier
    ) -> (light: TerminalPalette?, dark: TerminalPalette?) {
        guard let themePaths else { return (nil, nil) }
        let dir = directory?.path ?? temporaryDirectory
        func probe(_ side: TerminalThemeBrightness, path: String) -> TerminalPalette? {
            let file = (dir as NSString).appendingPathComponent("ghostty-theme-probe-\(processID)-\(side.rawValue).weir")
            return probePalette(
                themePath: path,
                file: file,
                directory: dir,
                includeUserConfig: includeUserConfig,
                userConfigPath: userConfigPath
            )
        }
        return (probe(.light, path: themePaths.light), probe(.dark, path: themePaths.dark))
    }

    private static func probePalette(
        themePath: String,
        file: String,
        directory: String,
        includeUserConfig: Bool,
        userConfigPath: String?
    ) -> TerminalPalette? {
        guard let line = themeLine(light: themePath, dark: themePath) else { return nil }
        do {
            try TestWriteGuard.check(URL(fileURLWithPath: file))
            try? FileManager.default.createDirectory(atPath: directory, withIntermediateDirectories: true)
            try (line + "\n").write(toFile: file, atomically: true, encoding: .utf8)
        } catch {
            log.error("theme probe write failed: \(String(describing: error), privacy: .private)")
            return nil
        }
        defer { try? FileManager.default.removeItem(atPath: file) }
        guard let cfg = ghostty_config_new() else {
            log.error("ghostty_config_new() returned nil during theme read-back")
            return nil
        }
        defer { ghostty_config_free(cfg) }
        // Deliberately not `makeConfig`: that records a read of the user
        // config, which Integrations reports to the person.
        if includeUserConfig {
            if let userConfigPath {
                userConfigPath.withCString { ghostty_config_load_file(cfg, $0) }
            } else {
                ghostty_config_load_default_files(cfg)
            }
        }
        file.withCString { ghostty_config_load_file(cfg, $0) }
        ghostty_config_finalize(cfg)
        return palette(of: cfg)
    }

    /// Reads `background`, `foreground`, and the first 16 `palette` entries
    /// from a finalized config.
    private static func palette(of cfg: ghostty_config_t) -> TerminalPalette? {
        func color(_ key: String) -> RGB8? {
            var value = ghostty_config_color_s()
            let isRead = key.withCString { ghostty_config_get(cfg, &value, $0, UInt(key.utf8.count)) }
            return isRead ? RGB8(r: value.r, g: value.g, b: value.b) : nil
        }
        guard let background = color("background"), let foreground = color("foreground") else { return nil }
        var palette = ghostty_config_palette_s()
        let key = "palette"
        let isRead = key.withCString { ghostty_config_get(cfg, &palette, $0, UInt(key.utf8.count)) }
        guard isRead else { return nil }
        let ansi = withUnsafeBytes(of: &palette.colors) { raw in
            raw.bindMemory(to: ghostty_config_color_s.self).prefix(TerminalPalette.ansiCount).map {
                RGB8(r: $0.r, g: $0.g, b: $0.b)
            }
        }
        return TerminalPalette(background: background, foreground: foreground, ansi: ansi)
    }

    /// One `keybind = …` line per `WeirShortcutAction` with a
    /// configured trigger. Ghostty-dispatched actions
    /// (`ghosttyAction != nil`) emit the real action so libghostty
    /// fires it when the terminal has focus. Menu-owned actions
    /// (`ghosttyAction == nil`) emit `=ignore` — a disabled menu
    /// item lets the keystroke fall through to the focused
    /// terminal, and without `ignore` libghostty would type the
    /// literal character ("j", "R", …). An enabled menu item
    /// consumes the event before libghostty sees it, so `ignore`
    /// only fires on the disabled path.
    private static func actionKeybindLines(settings: WeirSettings) -> [String] {
        var out: [String] = []
        for action in WeirShortcutAction.allCases {
            guard let shortcut = settings.keyboard.shortcut(for: action) else { continue }
            // `KeyboardSettings.normalize` retires such a key when settings
            // load; we check again for a caller that builds settings without it.
            guard shortcut.hasWritableKey else {
                log.error("Skipped a keybind whose key cannot be written for \(action.rawValue, privacy: .public)")
                continue
            }
            let rhs = action.ghosttyAction ?? "ignore"
            out.append("keybind = \(shortcut.ghosttyTrigger)=\(rhs)")
        }
        return out
    }

    /// `=ignore` for ⌘1…⌘9 and ⌃⌘1…⌃⌘9, the menu's numbered jumps
    /// (`NumberShortcutCommands`). The menu disables a number with no tab or
    /// worktree behind it, and a disabled item lets the keystroke through
    /// to the terminal like any other: the binding is what drops it there,
    /// as it does for a menu-owned action's keys.
    private static func numberJumpKeybindLines() -> [String] {
        ReservedShortcuts.numberJumpTriggers.map { "keybind = \($0)=ignore" }
    }

    /// Write the config string to a stable temp file and return its
    /// path. Caller passes the path to `ghostty_config_load_file`.
    /// The same path is reused for live reloads — `update_config`
    /// looks at file mtime, so we overwrite atomically.
    ///
    /// A chosen theme Weir does not ship is read here and its color lines
    /// written first, to a copy in `themeCopyDirectory` (beside the config
    /// when `directory` is given) that the `theme` line names. The copy is
    /// named by its colors (`themeCopyPath`) and written only when no file
    /// has that name, so an existing copy, which the running config may
    /// name, is never rewritten. Older copies are removed
    /// once a config that no longer names them is in use
    /// (`removeStaleThemeCopies`). Returns `nil` when a copy or the config
    /// could not be written.
    static func writeConfigFile(
        settings: WeirSettings,
        resourcesDir: String?,
        directory: URL? = nil,
        processID: Int32 = ProcessInfo.processInfo.processIdentifier,
        themeCatalog: TerminalThemeCatalog? = nil
    ) -> String? {
        let dir = directory?.path ?? temporaryDirectory
        let copyDirectory = directory?.path ?? themeCopyDirectory
        let theme = resolveTheme(
            selection: settings.appearance.terminalTheme,
            resourcesDir: resourcesDir,
            catalog: themeCatalog
        )
        let paths = theme.map { themePaths(for: $0, directory: copyDirectory, processID: processID) }
        let body = makeConfigString(
            settings: settings,
            resourcesDir: resourcesDir,
            themePaths: paths,
            shell: defaultShell
        )
        // We isolate concurrent Dev and Release instances so one cannot replace
        // the file between another instance writing it and libghostty reading it.
        let name = "ghostty-config-\(processID).weir"
        let path = (dir as NSString).appendingPathComponent(name)
        do {
            // A test hands its own folder; the guard keeps one that names the
            // user's real data from being written to.
            try TestWriteGuard.check(URL(fileURLWithPath: path))
            try? FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
            for side in [TerminalThemeBrightness.light, .dark] {
                guard case let .sanitized(colors)? = theme?.source(for: side) else { continue }
                let copy = themeCopyPath(for: side, colors: colors, directory: copyDirectory, processID: processID)
                // The name is the content, so a file already there holds it.
                guard !FileManager.default.fileExists(atPath: copy) else { continue }
                SecureFileWrite.ensureUserOnlyDirectory(URL(fileURLWithPath: copyDirectory, isDirectory: true))
                try SecureFileWrite.writeAtomic(Data(colors.utf8), to: URL(fileURLWithPath: copy))
            }
            try body.write(toFile: path, atomically: true, encoding: .utf8)
            writtenThemePaths = paths
            return path
        } catch {
            log.error("config file write failed: \(String(describing: error), privacy: .private)")
            return nil
        }
    }

    // MARK: - Live reload

    /// When libghostty last read the person's own Ghostty config, at launch
    /// or in a reload; nil while it has not. Integrations compares the
    /// file's date with it to say an edit has not been read yet.
    private(set) static var userConfigReadAt: Date?

    /// Records that the user config was just read.
    static func noteUserConfigRead(at date: Date = Date()) {
        userConfigReadAt = date
    }

    /// Finalize a config and copy its diagnostics. A path validates that file;
    /// `nil` validates Ghostty's default user config. Runtime callers invoke
    /// this before adding Weir's generated layer so our errors are never
    /// attributed to the user's file.
    static func configDiagnostics(at path: String? = nil) -> [String]? {
        guard let cfg = ghostty_config_new() else {
            log.error("ghostty_config_new() returned nil during config validation")
            return nil
        }
        defer { ghostty_config_free(cfg) }
        if let path {
            path.withCString { ghostty_config_load_file(cfg, $0) }
        } else {
            ghostty_config_load_default_files(cfg)
        }
        ghostty_config_finalize(cfg)
        return GhosttyFFI.configDiagnostics(cfg)
    }

    /// Rebuild the libghostty config from the current `WeirSettings`
    /// and push it into the running app.
    ///
    /// Surfaces opened *before* this call retain settings that
    /// libghostty marks as new-terminal only (font family, ligatures,
    /// scrollback). Settings libghostty applies live (font size,
    /// theme, opacity, cursor) reach every running surface
    /// immediately.
    ///
    /// Returns diagnostics from the finalized user config. Throws if Weir's
    /// layer could not be written or no config could be created. The running
    /// config then retains its forced overrides and its theme copies. Once
    /// `install` returns, the copies it no longer names are removed.
    static func reloadConfig(
        settings: WeirSettings,
        resourcesDir: String?,
        includeUserConfig: Bool,
        directory: URL? = nil,
        themeCatalog: TerminalThemeCatalog? = nil,
        install: (ghostty_config_t) -> Void
    ) throws(GhosttyConfigReloadError) -> [String] {
        guard let path = writeConfigFile(
            settings: settings,
            resourcesDir: resourcesDir,
            directory: directory,
            themeCatalog: themeCatalog
        ) else {
            throw .layerWriteFailed
        }
        // Set by the write that just succeeded: the copies this config names.
        let themePaths = writtenThemePaths
        let diagnostics = includeUserConfig ? configDiagnostics() ?? [] : []
        guard let cfg = makeConfig(path: path, includeUserConfig: includeUserConfig) else {
            throw .configCreationFailed
        }
        // Ownership moves to the caller's GhosttyApp so a later conditional-state
        // soft reload uses this exact layered config rather than the startup copy.
        install(cfg)
        removeStaleThemeCopies(keeping: themePaths, directory: directory)
        log.notice("ghostty config reloaded")
        return diagnostics
    }

    /// Build a finalized libghostty config from the on-disk Weir
    /// config file. The caller owns the returned handle — pass it to
    /// exactly one `ghostty_*_update_config` call. `nil` when `path` is
    /// `nil` (the file could not be written): a config without Weir's layer
    /// lacks the forced overrides the compositor and review's paste rely
    /// on, so no config is better than that one.
    static func makeConfig(path: String?, includeUserConfig: Bool) -> ghostty_config_t? {
        guard let path else {
            log.error("Weir's config layer is missing; building no config")
            return nil
        }
        guard let cfg = ghostty_config_new() else {
            log.error("ghostty_config_new() returned nil")
            return nil
        }
        // Optional Layer 2: user's ~/.config/ghostty/config.
        // Forbidden keys still get neutralized because our forced
        // overrides append below them.
        if includeUserConfig {
            ghostty_config_load_default_files(cfg)
            noteUserConfigRead()
        }
        // Layer 3 + 4: Weir settings + forced overrides.
        path.withCString { ghostty_config_load_file(cfg, $0) }
        ghostty_config_finalize(cfg)
        return cfg
    }

    // MARK: - Mapping helpers

    /// Weir's `CursorStyle` → libghostty's `cursor-style` value.
    private static func mapCursorStyle(_ style: CursorStyle) -> String {
        switch style {
        case .block: "block"
        case .bar: "bar"
        case .underline: "underline"
        }
    }

    static func resolvedTerm(resourcesDir: String?) -> String {
        guard let resourcesDir else { return "xterm-256color" }
        let database = URL(fileURLWithPath: resourcesDir)
            .deletingLastPathComponent()
            .appendingPathComponent("terminfo/78/xterm-ghostty")
        return FileManager.default.fileExists(atPath: database.path)
            ? "xterm-ghostty"
            : "xterm-256color"
    }

